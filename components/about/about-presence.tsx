import Image from "next/image";
import type { CSSProperties } from "react";
import { RevealList } from "@/components/home/reveal-list";
import { Eyebrow } from "@/components/ui/eyebrow";
import { Icon } from "@/components/ui/icon";
import { company } from "@/src/content/company";
import type { Locale } from "@/src/i18n/config";
import { getDictionary } from "@/src/i18n/dictionaries";
import { ordinal } from "@/src/lib/format";
import { mapArcPath, mapHeight, mapWidth, toMapPercent } from "@/src/lib/world-map";

type Place = {
  key: string;
  /** Longitude/latitude of the marker. */
  coordinates: [number, number];
  /** Side of the marker the map label sits on, chosen so the three labels never collide. */
  label: "left" | "top" | "right";
  headquarters?: boolean;
};

/*
 * In company.locations order. Same coordinates as the homepage globe: Murcia and Dubai are
 * city coordinates; GFB lists Türkiye as a country without a city, so its marker sits at
 * the country's geographic centre and must not be read as an office.
 */
const places: Place[] = [
  { key: "spain", coordinates: [-1.13, 37.99], label: "left", headquarters: true },
  { key: "turkiye", coordinates: [35.24, 38.96], label: "top" },
  { key: "dubai", coordinates: [55.27, 25.2], label: "right" }
];

const headquarters = places[0]!;

/**
 * About GFB "International presence". Below 1100px the heading and location list keep their
 * previous layout from globals.css; the dotted world map, markers and route lines are the
 * desktop design, styled in app/styles/about-presence.css. The map dots are generated by
 * scripts/generate-world-map.ts with the same projection used here for markers and arcs.
 * Hovering a location highlights its marker (and the reverse) with CSS `:has()` only.
 */
export function AboutPresence({ locale }: { locale: Locale }) {
  const { about, home } = getDictionary(locale);
  const copy = about.presence;

  return (
    <section className="section presence-section section-dark">
      <RevealList as="div" className="shell presence-shell">
        <Eyebrow onDark>{copy.eyebrow}</Eyebrow>
        <div className="presence-heading">
          <h2>
            {copy.title} <span className="presence-section__accent">{copy.titleAccent}</span>
          </h2>
          <p>{copy.text}</p>
        </div>

        {/* Decorative: the list below carries the same information. */}
        <div
          className="presence-map"
          style={{ aspectRatio: `${mapWidth} / ${mapHeight}` } as CSSProperties}
          aria-hidden="true"
        >
          <Image
            src="/images/about/world-dots.svg"
            alt=""
            width={mapWidth}
            height={mapHeight}
            unoptimized
            className="presence-map__dots"
          />
          <svg className="presence-map__lines" viewBox={`0 0 ${mapWidth} ${mapHeight}`} focusable="false">
            {places
              .filter((place) => place !== headquarters)
              .map((place, index) => (
                <path
                  key={place.key}
                  className="presence-map__arc"
                  data-place={place.key}
                  d={mapArcPath(headquarters.coordinates, place.coordinates, index === 0 ? 0.42 : 0.3)}
                  pathLength={1}
                  style={{ "--i": index } as CSSProperties}
                />
              ))}
          </svg>
          {places.map((place, index) => {
            const { left, top } = toMapPercent(...place.coordinates);
            return (
              <span
                key={place.key}
                className={place.headquarters ? "presence-map__place presence-map__place--hq" : "presence-map__place"}
                data-place={place.key}
                data-label={place.label}
                style={{ left: `${left}%`, top: `${top}%`, "--i": index } as CSSProperties}
              >
                <span className="presence-map__marker" />
                <span className="presence-map__label">
                  <strong>{place.headquarters ? company.address.locality : company.locations[index]?.[locale]}</strong>
                  <small>{place.headquarters ? home.world.headquarters : copy.presence}</small>
                </span>
              </span>
            );
          })}
        </div>

        <ul className="presence-list">
          {company.locations.map((location, index) => (
            <li key={location.en} data-place={places[index]?.key}>
              <span aria-hidden="true">{ordinal(index)}</span>
              <strong>{location[locale]}</strong>
              {index === 0 ? (
                <small>
                  <Icon name="pin" className="presence-list__pin" strokeWidth={1.6} />
                  {copy.headquarters}
                </small>
              ) : (
                <small className="presence-list__extra">
                  <Icon name="pin" className="presence-list__pin" strokeWidth={1.6} />
                  {copy.presence}
                </small>
              )}
            </li>
          ))}
        </ul>
      </RevealList>
    </section>
  );
}
