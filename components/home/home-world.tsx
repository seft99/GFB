import Image from "next/image";
import type { CSSProperties } from "react";
import { TextLink } from "@/components/ui/button-link";
import { Eyebrow } from "@/components/ui/eyebrow";
import { Icon, type IconName } from "@/components/ui/icon";
import { company } from "@/src/content/company";
import type { Locale } from "@/src/i18n/config";
import { getDictionary } from "@/src/i18n/dictionaries";
import { paths } from "@/src/i18n/routes";
import { arcPath, globeExtent, project, toPercent } from "@/src/lib/globe";
import { RevealList } from "./reveal-list";

type Place = {
  key: string;
  /** Index into company.locations, which holds the localized names. */
  location: number;
  /** Longitude/latitude of the marker. */
  coordinates: [number, number];
  /** City shown under the name, when the marker stands for a city. */
  city?: string;
  headquarters?: boolean;
};

/*
 * Murcia and Dubai are city coordinates. GFB lists Türkiye as a country without a city, so
 * its marker sits at the country's geographic centre and must not be read as an office.
 */
const places: Place[] = [
  { key: "spain", location: 0, coordinates: [-1.13, 37.99], city: "Murcia", headquarters: true },
  { key: "turkiye", location: 1, coordinates: [35.24, 38.96] },
  { key: "dubai", location: 2, coordinates: [55.27, 25.2] }
];

const headquarters = places[0]!;
const indicatorIcons: IconName[] = ["pin"];
const viewBox = `${-globeExtent} ${-globeExtent} ${2 * globeExtent} ${2 * globeExtent}`;

/**
 * Homepage "International coordination". The copy and the original location map keep their
 * previous markup for tablet and mobile; the dotted globe and indicators are the desktop
 * design (≥ 1100px), styled in app/styles/home-world.css. The globe dots are generated by
 * scripts/generate-globe.ts with the same projection used here for markers and arcs.
 */
export function HomeWorld({ locale }: { locale: Locale }) {
  const { home } = getDictionary(locale);
  const copy = home.world;

  return (
    <section className="section world-section section-dark world">
      <div className="shell world-grid">
        <div className="world__copy">
          <Eyebrow onDark>{copy.eyebrow}</Eyebrow>
          <h2>{copy.title}</h2>
          <p>{copy.text}</p>
          <TextLink href={paths.page(locale, "about")} tone="light">
            {copy.cta}
          </TextLink>
          <ul className="world__indicators" aria-label={copy.indicatorsLabel}>
            {copy.indicators.map((indicator, index) => (
              <li key={indicator.label}>
                <span className="world__indicator-icon" aria-hidden="true">
                  <Icon name={indicatorIcons[index] ?? "check"} strokeWidth={1.5} />
                </span>
                <span>
                  <strong>{indicator.value}</strong> <span>{indicator.label}</span>
                </span>
              </li>
            ))}
          </ul>
        </div>

        <div className="location-map" aria-label={copy.mapLabel} role="group">
          <div className="map-grid" aria-hidden="true" />
          {company.locations.map((location, index) => (
            <div className={`location location--${index + 1}`} key={location.en}>
              <i />
              <span>{location[locale]}</span>
            </div>
          ))}
        </div>

        <RevealList as="div" className="world__globe">
          <div className="world__sphere">
            <Image
              src="/images/home/globe-dots.svg"
              alt=""
              width={2020}
              height={2020}
              unoptimized
              className="world__dots"
            />
            <svg className="world__lines" viewBox={viewBox} aria-hidden="true" focusable="false">
              <ellipse className="world__orbit" cx="-60" cy="120" rx="1180" ry="560" transform="rotate(-14)" />
              {places
                .filter((place) => place !== headquarters)
                .map((place, index) => (
                  <path
                    key={place.key}
                    className="world__arc"
                    data-arc={place.key}
                    d={arcPath(headquarters.coordinates, place.coordinates, index === 0 ? 0.7 : 0.42)}
                    pathLength={1}
                    style={{ "--i": index } as CSSProperties}
                  />
                ))}
            </svg>
            <ul className="world__places" aria-label={copy.mapLabel}>
              {places.map((place, index) => {
                const { left, top } = toPercent(project(...place.coordinates));
                const name = company.locations[place.location]?.[locale];
                return (
                  <li
                    key={place.key}
                    className={place.headquarters ? "world__place world__place--hq" : "world__place"}
                    data-place={place.key}
                    style={{ left: `${left}%`, top: `${top}%`, "--i": index } as CSSProperties}
                  >
                    <span className="world__marker" aria-hidden="true" />
                    <span className="world__label">
                      <strong>{name}</strong>
                      <small>
                        {/* Spain is labelled by its city; Türkiye and Dubai only as a presence. */}
                        {place.city ?? copy.presence}
                      </small>
                    </span>
                  </li>
                );
              })}
            </ul>
          </div>
        </RevealList>
      </div>
    </section>
  );
}
