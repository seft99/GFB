/**
 * Audit of the "More in this family" section of every product-detail page (EN/ES):
 * docs/related-resources-audit.md and docs/migration-data/related-resources-audit.json.
 * Uses the same data as the page (src/migration/related-resources.ts).
 * Run: node scripts/build-related-audit.ts
 */
import { writeFileSync } from "node:fs";
import { getDivisionById } from "../src/content/catalog.ts";
import { locales } from "../src/i18n/config.ts";
import { paths } from "../src/i18n/routes.ts";
import type { Section } from "../src/migration/content.ts";
import { familyOf } from "../src/migration/families.ts";
import { detailPaths, legacyPage } from "../src/migration/manifest.ts";
import { familyResources, relatedEntries } from "../src/migration/related-resources.ts";

const contentLinks = (sections: Section[]) =>
  new Set(
    sections.flatMap((section) => [
      ...(section.link ? [section.link] : []),
      ...section.items.flatMap((item) => (item.type === "links" ? item.paths : []))
    ])
  );

const rows = detailPaths.flatMap((path) =>
  locales.map((locale) => {
    const family = familyOf(path)!;
    const division = getDivisionById(family.parent.division)!;
    const category = division.categories.find((item) => item.id === family.parent.category);
    const config = familyResources(path, locale, category ? paths.category(locale, division, category) : undefined)!;
    const linked = contentLinks(legacyPage(path)![locale].sections);
    const shown = relatedEntries(config, path, linked);
    const identity = config.entries.find((entry) => entry.resources.some((item) => item.path === path))!;
    return {
      path,
      locale,
      family: family.id,
      identity: identity.title,
      familyEntries: config.entries.length,
      familyResources: config.entries.reduce((sum, entry) => sum + entry.resources.length, 0),
      shownEntries: shown.length,
      shownResources: shown.reduce((sum, entry) => sum + entry.resources.length, 0),
      ownAlternatives: shown
        .filter((entry) => entry.id === identity.id)
        .flatMap((entry) => entry.resources.map((item) => item.kind)),
      excludedAsContentLinks: [...linked].filter((item) => family.paths.includes(item)).length,
      directoryHref: config.directoryHref ?? null,
      rendered: shown.length > 0
    };
  })
);

writeFileSync("docs/migration-data/related-resources-audit.json", `${JSON.stringify(rows, null, 2)}\n`);

const en = rows.filter((row) => row.locale === "en");
const families = [...new Set(en.map((row) => row.family))];
const lines = [
  "# More in this family — coverage audit",
  "",
  "Generated by `node scripts/build-related-audit.ts` from the data the pages use",
  "(`src/migration/related-resources.ts`). Per page and language: `docs/migration-data/related-resources-audit.json`.",
  "",
  `- Detail pages: ${detailPaths.length} × ${locales.length} languages = ${rows.length} pages.`,
  `- Pages rendering the section: ${rows.filter((row) => row.rendered).length}; without related destinations (section omitted): ${rows.filter((row) => !row.rendered).length}.`,
  "",
  "| Family | Identities | Resources | Directory link (EN) |",
  "| --- | ---: | ---: | --- |",
  ...families.map((id) => {
    const row = en.find((item) => item.family === id)!;
    return `| ${id} | ${row.familyEntries} | ${row.familyResources} | ${row.directoryHref ? `\`${row.directoryHref}\`` : "—"} |`;
  }),
  "",
  "## Pages (EN; ES has the same structure)",
  "",
  "| Page | Identity | Cards | Links | Own other page | Not repeated (in content) |",
  "| --- | --- | ---: | ---: | --- | ---: |",
  ...en.map(
    (row) =>
      `| \`${row.path}\` | ${row.identity} | ${row.shownEntries} | ${row.shownResources} | ${row.ownAlternatives.join(", ") || "—"} | ${row.excludedAsContentLinks || "—"} |`
  ),
  ""
];
writeFileSync("docs/related-resources-audit.md", lines.join("\n"));
console.log(`${rows.length} pages; ${rows.filter((row) => row.rendered).length} with the section`);
